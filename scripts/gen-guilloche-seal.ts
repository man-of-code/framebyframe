import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const CX = 500;
const CY = 500;

/** Base curve P(a, d, m, N): a closed polyline of N points, 1 decimal. */
function curve(a: number, d: number, m: number, n: number): string {
  const pts: string[] = [];
  for (let i = 0; i < n; i += 1) {
    const t = (2 * Math.PI * i) / n;
    const x = CX + a * Math.cos(t) + d * Math.cos(m * t);
    const y = CY + a * Math.sin(t) - d * Math.sin(m * t);
    pts.push(`${i === 0 ? "M" : "L"}${x.toFixed(1)} ${y.toFixed(1)}`);
  }
  return `${pts.join(" ")} Z`;
}

const deg = (rad: number): number => (rad * 180) / Math.PI;

function use(id: "o" | "i", theta: number, scale: number): string {
  return `<use href="#${id}" transform="translate(500 500) rotate(${theta.toFixed(3)}) scale(${scale.toFixed(4)}) translate(-500 -500)"/>`;
}

const outer: string[] = [];
for (let k = 0; k < 18; k += 1) {
  const phi = 0.2 + (2 * Math.PI * k) / 18;
  outer.push(use("o", deg(-phi / 12), 1 - (0.035 * k) / 18));
}
const inner: string[] = [];
for (let k = 0; k < 14; k += 1) {
  const phi = 0.9 - (2 * Math.PI * k) / 14;
  inner.push(use("i", deg(-phi / 20), 1 - (0.05 * k) / 14));
}

const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1000 1000">
<!-- Geometry adapted from MengTo/threeui@68802d5428071ada5c20db8094b1649e6bb770ed src/shaders/neuform-isolated/sources/kinetic-lathe-certificate.html rosette() (MIT, see src/vendor/threeui/LICENSE). Generated by scripts/gen-guilloche-seal.ts. -->
<defs><path id="o" d="${curve(314.4, 103.2, 11, 360)}"/><path id="i" d="${curve(160.8, 55.2, 19, 300)}"/></defs>
<g fill="none" stroke="#000" stroke-width="1.4">
<g stroke-opacity="0.5">
${outer.join("\n")}
</g>
<g stroke-opacity="0.5">
${inner.join("\n")}
</g>
<circle cx="500" cy="500" r="446.4" stroke-width="3"/>
<circle cx="500" cy="500" r="465.6" stroke-width="6"/>
<circle cx="500" cy="500" r="33.6" stroke-width="3"/>
<circle cx="500" cy="500" r="19.2" stroke-width="2"/>
</g>
</svg>
`;

const out = fileURLToPath(new URL("../src/assets/ornaments/guilloche-seal.svg", import.meta.url));
writeFileSync(out, svg);
console.log(`wrote ${out} (${svg.length} bytes)`);
